/**
 * Everything the interface needs to render, in one snapshot.
 *
 * `hydrated` is false only for the server render and the first client render, so
 * the markup the browser receives matches the markup React hydrates, and the
 * stored record arrives on the next snapshot. `discarded` and `repaired` explain
 * a record that could not be used or had to be adjusted, so the page can say so
 * rather than appear to forget.
 */
export interface PackingSnapshot {
  readonly state: PackingState;
  readonly discarded: boolean;
  readonly repaired: boolean;
  readonly hydrated: boolean;
}

export interface PackingStore {
  readonly subscribe: (listener: () => void) => () => void;
  /** The client snapshot. Stable between changes, so React does not loop. */
  readonly getSnapshot: () => PackingSnapshot;
  /** The snapshot the server renders, which is always the default. */
  readonly getServerSnapshot: () => PackingSnapshot;
  /** Applies an update, persists it and notifies subscribers. */
  readonly update: (updater: (current: PackingState) => PackingState) => void;
}

interface StoreCache {
  readonly storage: StorageLike | null;
  readonly snapshot: PackingSnapshot;
}

/**
 * Builds the store the checklist reads from.
 *
 * localStorage is treated as the single source of truth, exactly as the site's
 * edition choice is: reading happens through `useSyncExternalStore`, so the
 * server always renders the default and the stored record replaces it on the
 * first client snapshot. A write can be refused (private mode, blocked site
 * data, a full quota), so the last committed snapshot is cached in memory and
 * keeps answering for the rest of the visit.
 *
 * @param fallbackEdition The edition used when no record is stored.
 */
export function createPackingStore(fallbackEdition: PackingEdition = "belgium"): PackingStore {
  const serverSnapshot: PackingSnapshot = {
    state: defaultPackingState(fallbackEdition),
    discarded: false,
    repaired: false,
    hydrated: false,
  };

  let cache: StoreCache | null = null;
  const listeners = new Set<() => void>();

  const currentStorage = (): StorageLike | null => safeLocalStorage();

  const read = (storage: StorageLike | null): PackingSnapshot => {
    const loaded = loadPackingState(storage, fallbackEdition);
    return {
      state: loaded.state,
      discarded: loaded.discarded,
      repaired: loaded.repaired,
      hydrated: true,
    };
  };

  const emit = (): void => {
    for (const listener of listeners) listener();
  };

  const getSnapshot = (): PackingSnapshot => {
    const storage = currentStorage();
    // A replaced Storage object means a different document context, so the cache
    // no longer describes it and storage is read again.
    if (cache === null || cache.storage !== storage) {
      cache = { storage, snapshot: read(storage) };
    }
    return cache.snapshot;
  };

  const handleStorage = (event: StorageEvent): void => {
    if (event.key !== PACKING_STORAGE_KEY && event.key !== null) return;
    const storage = currentStorage();
    cache = { storage, snapshot: read(storage) };
    emit();
  };

  const subscribe = (listener: () => void): (() => void) => {
    listeners.add(listener);
    // One window listener for the whole page, attached while anything subscribes.
    if (listeners.size === 1) window.addEventListener("storage", handleStorage);
    return () => {
      listeners.delete(listener);
      if (listeners.size === 0) window.removeEventListener("storage", handleStorage);
    };
  };

  const update = (updater: (current: PackingState) => PackingState): void => {
    const storage = currentStorage();
    const current = cache !== null && cache.storage === storage ? cache.snapshot : getSnapshot();
    const nextState = updater(current.state);
    if (nextState === current.state) return;
    savePackingState(storage, nextState);
    cache = {
      storage,
      snapshot: {
        state: nextState,
        // A reader's own action has replaced whatever was wrong with the stored
        // record, so the notices stop being relevant at that point.
        discarded: false,
        repaired: false,
        hydrated: true,
      },
    };
    emit();
  };

  return { subscribe, getSnapshot, getServerSnapshot: () => serverSnapshot, update };
}
