import { z } from "zod";
import {
  packingEditionSchema,
  packingStaySchema,
  type PackingEdition,
  type PackingStay,
} from "./packing-catalogue";
import { defaultStayFor, isStayForEdition, normaliseCustomLabel } from "./packing-logic";

/**
 * The packing tool's saved state.
 *
 * Everything here is untrusted input: localStorage can hold whatever a previous
 * version wrote, a different app on a shared origin, or something hand-edited in
 * the dev tools. So the stored record is parsed through the schema below and a
 * failure discards it rather than throwing into the render.
 *
 * The shape is deliberately small and bounded:
 *
 * - at most {@link MAX_PACKED_IDS} packed ids, each a short slug;
 * - at most {@link MAX_CUSTOM_ITEMS} reader items, each {@link MAX_CUSTOM_LABEL}
 *   characters, stored already trimmed and whitespace-collapsed;
 * - a whole-record length cap, so a hostile or corrupt value cannot make the
 *   parse do unbounded work or fill the quota.
 *
 * The record is only ever written to one key, {@link PACKING_STORAGE_KEY}.
 */

/** The one localStorage key this tool reads and writes. */
export const PACKING_STORAGE_KEY = "tml-packing-v1";

/** Reader items are capped so the list stays scannable and the record stays small. */
export const MAX_CUSTOM_ITEMS = 60;

/** The longest reader item text accepted, in characters. */
export const MAX_CUSTOM_LABEL = 80;

/**
 * Packed ids are capped well above the largest possible list (the catalogue is
 * smaller than this) so the cap never shows to a reader but still bounds a
 * tampered record.
 */
export const MAX_PACKED_IDS = 400;

/**
 * The longest stored JSON string this tool will parse, in characters.
 *
 * The legitimate worst case — every item and every reader item packed, each id
 * a full-length slug — is comfortably under this; anything longer is not
 * something this tool wrote.
 */
export const MAX_STORED_LENGTH = 64_000;

/** A reader item's id. Generated by the tool, never typed by a reader. */
const customIdSchema = z
  .string()
  .regex(/^custom-[a-z0-9]{1,16}$/, { error: "custom item id must be custom-<alphanumerics>" });

export const customItemSchema = z.strictObject({
  id: customIdSchema,
  label: z
    .string()
    .trim()
    .min(1, { error: "an item cannot be empty" })
    .max(MAX_CUSTOM_LABEL, { error: `an item must be ${MAX_CUSTOM_LABEL} characters or fewer` }),
});
export type CustomItem = z.infer<typeof customItemSchema>;

export const packingStateSchema = z
  .strictObject({
    edition: packingEditionSchema,
    stay: packingStaySchema,
    packed: z.array(z.string().min(1).max(80)).max(MAX_PACKED_IDS),
    custom: z.array(customItemSchema).max(MAX_CUSTOM_ITEMS),
  })
  .superRefine((state, ctx) => {
    /*
      The schema checks shape only, not whether `stay` belongs to `edition`.

      A mismatch is legitimate rather than corrupt: the catalogue can gain or
      lose a stay between visits, so an older record can name a stay that no
      longer exists for its edition. Rejecting the whole record there would throw
      away the reader's ticks over one field, so the pair is reconciled by
      `repairPackingState` instead, which keeps everything else.
    */
    const seenPacked = new Set<string>();
    state.packed.forEach((id, index) => {
      if (seenPacked.has(id)) {
        ctx.addIssue({ code: "custom", path: ["packed", index], message: "duplicate packed id" });
      }
      seenPacked.add(id);
    });
    const seenCustom = new Set<string>();
    state.custom.forEach((item, index) => {
      if (seenCustom.has(item.id)) {
        ctx.addIssue({ code: "custom", path: ["custom", index, "id"], message: "duplicate custom id" });
      }
      seenCustom.add(item.id);
    });
  });

export type PackingState = z.infer<typeof packingStateSchema>;

/** The state a first visit shows: the edition's first stay, nothing packed, no own items. */
export function defaultPackingState(edition: PackingEdition = "belgium"): PackingState {
  return { edition, stay: defaultStayFor(edition), packed: [], custom: [] };
}

/**
 * Moves a state onto an edition or stay it can legitimately hold.
 *
 * A stored record from another edition is kept rather than thrown away: it is
 * the reader's own ticks. Only the stay is forced onto the edition's first stay
 * when the pair cannot both be true, which is the one case the schema rejects
 * and a reader cannot produce through the interface.
 */
export function repairPackingState(state: PackingState): { state: PackingState; repaired: boolean } {
  if (isStayForEdition(state.stay, state.edition)) return { state, repaired: false };
  return { state: { ...state, stay: defaultStayFor(state.edition) }, repaired: true };
}

/**
 * The next free reader-item id.
 *
 * Ids are `custom-<n>` with `n` one higher than the largest already in use, so
 * an id is never reused after a removal and two items can never collide. The
 * search is bounded by {@link MAX_CUSTOM_ITEMS}, so a tampered id such as
 * `custom-z` cannot loop forever.
 */
export function nextCustomId(existing: readonly { readonly id: string }[]): string {
  let highest = 0;
  for (const item of existing) {
    const match = /^custom-(\d{1,16})$/.exec(item.id);
    if (match === null) continue;
    const value = Number(match[1]);
    if (Number.isSafeInteger(value) && value > highest) highest = value;
  }
  return `custom-${highest + 1}`;
}

export interface AddCustomResult {
  readonly state: PackingState;
  /** Why the item was not added, or null when it was. */
  readonly problem: "empty" | "too-long" | "duplicate" | "full" | null;
}

/**
 * Adds a reader item.
 *
 * The label is cleaned first (trimmed, whitespace collapsed), so "Sleep mask"
 * and "  Sleep   mask " are recognised as the same item rather than stored
 * twice. The comparison is case-insensitive for the same reason.
 */
export function addCustomItem(state: PackingState, rawLabel: string): AddCustomResult {
  const label = normaliseCustomLabel(rawLabel);
  if (label === null) return { state, problem: "empty" };
  if (label.length > MAX_CUSTOM_LABEL) return { state, problem: "too-long" };
  if (state.custom.length >= MAX_CUSTOM_ITEMS) return { state, problem: "full" };

  const key = label.toLowerCase();
  if (state.custom.some((item) => item.label.toLowerCase() === key)) {
    return { state, problem: "duplicate" };
  }

  const item: CustomItem = { id: nextCustomId(state.custom), label };
  return {
    state: { ...state, custom: [...state.custom, item] },
    problem: null,
  };
}

/**
 * Removes a reader item and its packed tick together.
 *
 * The tick is dropped with the item so a later item that happens to reuse the
 * id cannot arrive already ticked.
 */
export function removeCustomItem(state: PackingState, id: string): PackingState {
  return {
    ...state,
    custom: state.custom.filter((item) => item.id !== id),
    packed: state.packed.filter((packedId) => packedId !== id),
  };
}

/** Adds or removes one packed id. */
export function togglePacked(state: PackingState, id: string): PackingState {
  if (state.packed.includes(id)) {
    return { ...state, packed: state.packed.filter((packedId) => packedId !== id) };
  }
  if (state.packed.length >= MAX_PACKED_IDS) return state;
  return { ...state, packed: [...state.packed, id] };
}

/**
 * Clears every tick, keeping the edition, the stay and the reader's own items.
 *
 * "Reset" means "start the list again", not "delete my own items": removing
 * those would be a second, separate action the reader did not ask for.
 */
export function resetTicks(state: PackingState): PackingState {
  return { ...state, packed: [] };
}

