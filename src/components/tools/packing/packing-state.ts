/** The minimal Storage surface used here, so a test can supply its own. */
export interface StorageLike {
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
  removeItem(key: string): void;
}

/** Returns localStorage, or null when it cannot be reached at all. */
export function safeLocalStorage(): StorageLike | null {
  try {
    if (typeof window === "undefined") return null;
    return window.localStorage;
  } catch {
    // Reading the property throws outright when site data is blocked.
    return null;
  }
}

export interface LoadedPackingState {
  readonly state: PackingState;
  /**
   * True when a stored value existed but could not be used. The page turns this
   * into a short notice instead of appearing to forget silently.
   */
  readonly discarded: boolean;
  readonly repaired: boolean;
}

/**
 * Reads the saved state.
 *
 * Never throws. An unreadable storage object, an oversized value, invalid JSON
 * and a record that fails the schema all resolve to the default state with
 * `discarded` set, so the page can say what happened.
 */
export function loadPackingState(
  storage: StorageLike | null,
  fallbackEdition: PackingEdition = "belgium",
): LoadedPackingState {
  const fallback = defaultPackingState(fallbackEdition);

  if (storage === null) return { state: fallback, discarded: false, repaired: false };

  let raw: string | null = null;
  try {
    raw = storage.getItem(PACKING_STORAGE_KEY);
  } catch {
    return { state: fallback, discarded: false, repaired: false };
  }

  if (raw === null || raw === "") return { state: fallback, discarded: false, repaired: false };
  if (raw.length > MAX_STORED_LENGTH) return { state: fallback, discarded: true, repaired: false };

  let parsed: unknown;
  try {
    parsed = JSON.parse(raw) as unknown;
  } catch {
    return { state: fallback, discarded: true, repaired: false };
  }

  const result = packingStateSchema.safeParse(parsed);
  if (!result.success) return { state: fallback, discarded: true, repaired: false };

  const repairedState = repairPackingState(result.data);
  return { state: repairedState.state, discarded: false, repaired: repairedState.repaired };
}

/**
 * Writes the state, ignoring a refusal.
 *
 * A browser that blocks storage or is over quota must still give a working
 * checklist, so a failed write is swallowed and the in-memory state carries on
 * for the rest of the visit. The length guard is a last line of defence against
 * writing a record this tool would refuse to read back.
 */
export function savePackingState(storage: StorageLike | null, state: PackingState): void {
  if (storage === null) return;
  let serialised: string;
  try {
    serialised = JSON.stringify(state);
  } catch {
    return;
  }
  if (serialised.length > MAX_STORED_LENGTH) return;
  try {
    storage.setItem(PACKING_STORAGE_KEY, serialised);
  } catch {
    // Private mode, blocked site data, or a full quota.
  }
}

/** Removes the stored record, ignoring a refusal. */
export function clearPackingState(storage: StorageLike | null): void {
  if (storage === null) return;
  try {
    storage.removeItem(PACKING_STORAGE_KEY);
  } catch {
    // Nothing to do: the state is memory-only for the rest of the visit.
  }
}

/** The stay a state should show after the reader picks a new edition. */
export function stayAfterEditionChange(edition: PackingEdition, currentStay: PackingStay): PackingStay {
  return isStayForEdition(currentStay, edition) ? currentStay : defaultStayFor(edition);
}

